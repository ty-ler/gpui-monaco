#!/usr/bin/env python3
"""Lists the command ids Monaco registers in
vendor/vscode/src/vs/editor/{browser/coreCommands.ts,browser/editorExtensions.ts,
contrib/**/browser,standalone/browser}: editor actions, editor commands and
`CommandsRegistry` commands, one per line with the file that registers it.

The list is checked in as crates/gpui-monaco/tests/fixtures/monaco_command_ids.txt;
tests/commands.rs asserts that each id resolves through `CodeEditor::trigger`
(except the workbench-only ones it lists).

Usage: script/porting/monaco_command_ids.py [path/to/vscode/src/vs/editor] \
           > crates/gpui-monaco/tests/fixtures/monaco_command_ids.txt
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EDITOR = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "vendor/vscode/src/vs/editor"

CONSTANT = re.compile(
    r"class\s+(\w+)|(?:static\s+(?:readonly\s+)?|const\s+)(\w+)\s*(?::\s*\w+)?\s*=\s*['\"]([^'\"]+)['\"]"
    r"|^\s*(\w+)\s*:\s*'([^']+)',?$",
    re.M,
)
# The first `id` of a command or action descriptor.
OPENER = re.compile(r"super\([^{();]*\{|register(?!Configuration)\w*\(\s*(?:new\s+\w+\([^{();]*)?\{")
# `registerOverwritableCommand(Handler.Type)` registers `type` and
# `default:type` (`Handler` is `common/editorCommon.ts`'s enum).
# `static ID = someConstant;`, resolved once the constants are known.
CONSTANT_ALIAS = re.compile(r"class\s+(\w+)|static\s+(?:readonly\s+)?(\w+)\s*=\s*([A-Za-z_]\w*);")
ALIAS = re.compile(r"registerCommandAlias\(\s*'([^']+)'")
OVERWRITABLE = re.compile(r"registerOverwritableCommand\(Handler\.(\w+)")
ID = re.compile(r"\bid\s*:\s*([A-Za-z_][\w.]*|'[^']+'|\"[^\"]+\")")
BY_NAME = re.compile(r"register(?:Command|ModelAndPositionCommand)\(\s*('[^']+'|\"[^\"]+\"|[A-Za-z_][\w.]*)")


def sources():
    yield EDITOR / "browser/coreCommands.ts"
    yield EDITOR / "browser/editorExtensions.ts"
    for base in (EDITOR / "contrib", EDITOR / "standalone/browser"):
        for path in sorted(base.rglob("*.ts")):
            parts = path.relative_to(EDITOR).parts
            if "test" in parts or path.name.endswith(".d.ts"):
                continue
            if base.name == "contrib" and "browser" not in parts:
                continue
            yield path


def main():
    files = list(sources())
    constants = {}
    for path in files:
        cls = None
        for m in CONSTANT.finditer(path.read_text()):
            if m.group(1):
                cls = m.group(1)
                continue
            if m.group(4):
                # An object literal's property, e.g. `FIND_IDS.StartFindAction`.
                constants.setdefault(m.group(4), m.group(5))
                continue
            constants.setdefault(m.group(2), m.group(3))
            if cls:
                constants[f"{cls}.{m.group(2)}"] = m.group(3)

    for path in files:
        cls = None
        for m in CONSTANT_ALIAS.finditer(path.read_text()):
            if m.group(1):
                cls = m.group(1)
            elif cls and m.group(3) in constants:
                constants[f"{cls}.{m.group(2)}"] = constants[m.group(3)]

    def resolve(expr):
        if expr[0] in "'\"":
            return expr[1:-1]
        return constants.get(expr) or constants.get(expr.split(".")[-1])

    ids = {}
    for path in files:
        text = path.read_text()
        rel = str(path.relative_to(EDITOR))
        found = []
        for opener in OPENER.finditer(text):
            m = ID.search(text, opener.end(), opener.end() + 200)
            if m:
                found.append(m.group(1))
        found += [m.group(1) for m in BY_NAME.finditer(text)]
        found += ["'" + m.group(1) + "'" for m in ALIAS.finditer(text)]
        for m in OVERWRITABLE.finditer(text):
            handler = "'" + m.group(1)[0].lower() + m.group(1)[1:] + "'"
            found += [handler, "'default:" + handler[1:]]
        for expr in found:
            value = resolve(expr)
            # Menu ids, contribution ids and the like aren't commands.
            if (
                value
                and re.fullmatch(r"[A-Za-z_][\w.:-]*", value)
                and not value.startswith("editor.contrib.")
            ):
                ids.setdefault(value, rel)
    print("# Generated by script/porting/monaco_command_ids.py from vendor/vscode;")
    print("# Monaco's command ids and the file registering each.")
    for command_id in sorted(ids):
        print(f"{command_id}\t{ids[command_id]}")


if __name__ == "__main__":
    main()
