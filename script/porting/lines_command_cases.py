#!/usr/bin/env python3
"""Extracts the copy/move lines command tests from Monaco's
vendor/vscode/src/vs/editor/contrib/linesOperations/test/browser/{copyLinesCommand,moveLinesCommand}.test.ts
into a Rust test file. Only calls of the language-agnostic helpers
(testCopyLinesDownCommand, testCopyLinesUpCommand, testMoveLinesDownCommand,
testMoveLinesUpCommand) are ported; tests using indentation/onEnter rules use
other helpers and are skipped.

Usage: script/porting/lines_command_cases.py > crates/gpui-monaco/src/cursor/tests/lines_command_cases.rs
       cargo fmt --all
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / "vendor/vscode/src/vs/editor/contrib/linesOperations/test/browser"
FILES = ["copyLinesCommand.test.ts", "moveLinesCommand.test.ts"]
HELPERS = {
    "testCopyLinesDownCommand": "LinesCommand::CopyDown",
    "testCopyLinesUpCommand": "LinesCommand::CopyUp",
    "testMoveLinesDownCommand": "LinesCommand::MoveDown",
    "testMoveLinesUpCommand": "LinesCommand::MoveUp",
}

TOKEN = re.compile(r"""\s*(?:('(?:[^'\\]|\\.)*')|("(?:[^"\\]|\\.)*")|(\d+)|(new\s+Selection)|([\[\](),]))""")


def js_unescape(lit):
    body = lit[1:-1]
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c == "\\":
            n = body[i + 1]
            out.append({"n": "\n", "r": "\r", "t": "\t", "\\": "\\", "'": "'", '"': '"'}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def rust_str(s):
    out = ""
    for c in s:
        if c == "\\":
            out += "\\\\"
        elif c == '"':
            out += '\\"'
        elif c == "\n":
            out += "\\n"
        elif c == "\t":
            out += "\\t"
        elif ord(c) > 127:
            out += "\\u{%x}" % ord(c)
        else:
            out += c
    return '"' + out + '"'


def parse_args(src, pos):
    """Parses `(arg, arg, ...)` starting at the '(' at `pos`; returns (args, end)."""
    def value(i):
        m = TOKEN.match(src, i)
        if not m:
            raise ValueError(src[i:i + 40])
        if m.group(1) or m.group(2):
            return js_unescape(m.group(1) or m.group(2)), m.end()
        if m.group(3):
            return int(m.group(3)), m.end()
        if m.group(4):
            args, end = parse_args(src, m.end())
            return ("sel", args), end
        if m.group(5) == "[":
            items, i = [], m.end()
            while True:
                m2 = TOKEN.match(src, i)
                if m2.group(5) == "]":
                    return items, m2.end()
                if m2.group(5) == ",":
                    i = m2.end()
                    continue
                v, i = value(i)
                items.append(v)
        raise ValueError(src[i:i + 40])

    m = TOKEN.match(src, pos)
    assert m.group(5) == "(", src[pos:pos + 40]
    args, i = [], m.end()
    while True:
        m = TOKEN.match(src, i)
        if m and m.group(5) == ")":
            return args, m.end()
        if m and m.group(5) == ",":
            i = m.end()
            continue
        v, i = value(i)
        args.append(v)


def rust_sel(v):
    assert v[0] == "sel"
    return "sel({}, {}, {}, {})".format(*v[1])


def rust_lines(lines):
    return "&[" + ", ".join(rust_str(l) for l in lines) + "]"


def snake(name):
    s = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower()
    return s


print("// @generated by script/porting/lines_command_cases.py from Monaco's")
print("// src/vs/editor/contrib/linesOperations/test/browser/{copyLinesCommand,moveLinesCommand}.test.ts (MIT).")
print("// Tests using indentation or onEnter rules (other helpers) are not included.")
print()
print("use super::harness::sel;")
print("use super::lines_test::{LinesCommand, test_lines_command};")
names = set()
for f in FILES:
    src = (DIR / f).read_text(encoding="utf-8")
    for block in re.split(r"\n\ttest\(", src)[1:]:
        name = re.match(r"'((?:[^'\\]|\\.)*)'", block).group(1)
        calls = []
        for m in re.finditer(r"\b(" + "|".join(HELPERS) + r")(?=\()", block):
            args, _ = parse_args(block, m.end())
            if len(args) != 4:
                continue
            calls.append((HELPERS[m.group(1)], args))
        if not calls:
            continue
        fn = snake(Path(f).stem.replace(".test", "") + "_" + name)
        while fn in names:
            fn += "_"
        names.add(fn)
        print()
        print("#[test]")
        print(f"fn {fn}() {{")
        for kind, (lines, selection, expected_lines, expected_selection) in calls:
            print(
                f"    test_lines_command({kind}, {rust_lines(lines)}, {rust_sel(selection)}, "
                f"{rust_lines(expected_lines)}, {rust_sel(expected_selection)});"
            )
        print("}")
