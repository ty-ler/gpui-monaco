#!/usr/bin/env python3
"""Extracts the fixed insert/delete sequences from Monaco's piece tree tests
(vendor/vscode/.../pieceTreeTextBuffer.test.ts) into a Rust test data file.

Usage: script/porting/piece_tree_cases.py > crates/text/tests/monaco_piece_tree_cases.rs
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[2] / "vendor/vscode/src/vs/editor/test/common/model/pieceTreeTextBuffer/pieceTreeTextBuffer.test.ts"
STR = r"""('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")"""


def js_unescape(lit):
    body = lit[1:-1]
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c == "\\":
            n = body[i + 1]
            out.append({"n": "\n", "r": "\r", "t": "\t", "\\": "\\", "'": "'", '"': '"'}.get(n, n))
            i += 2
        else:
            out.append(c)
            i += 1
    return "".join(out)


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t") + '"'


src = SRC.read_text()
tests = re.split(r"\n\ttest\('", src)
suite = None
cases = []
for block in tests[1:]:
    name = block.split("'", 1)[0]
    body = block
    m = re.search(r"createTextBuffer\(\s*\[(.*?)\]\s*(,\s*(true|false))?\s*\)", body, re.S)
    if not m:
        continue
    initial = "".join(js_unescape(s) for s in re.findall(STR, m.group(1)))
    normalize = m.group(3) != "false"
    ops = []
    for op in re.finditer(r"\.(insert|delete)\(\s*(\d+)\s*,\s*(" + STR[1:-1] + r"|\d+)\s*\)", body):
        kind, offset, arg = op.group(1), int(op.group(2)), op.group(3)
        if kind == "insert":
            if not arg[0] in "'\"":
                break
            ops.append(f"Op::Insert({offset}, {rust_str(js_unescape(arg))})")
        else:
            ops.append(f"Op::Delete({offset}, {int(arg)})")
    if not ops:
        continue
    cases.append((name, initial, normalize, ops))

print("// @generated by script/porting/piece_tree_cases.py from Monaco's")
print("// src/vs/editor/test/common/model/pieceTreeTextBuffer/pieceTreeTextBuffer.test.ts (MIT).")
print("// Offsets and lengths are UTF-16 code units, as in Monaco; inputs are ASCII.")
print()
print("pub enum Op {\n    Insert(usize, &'static str),\n    Delete(usize, usize),\n}\n")
print("pub struct Case {\n    pub name: &'static str,\n    pub initial: &'static str,\n    pub ops: &'static [Op],\n}\n")
print("pub const CASES: &[Case] = &[")
for name, initial, normalize, ops in cases:
    print(f"    Case {{\n        name: {rust_str(name)},\n        initial: {rust_str(initial)},\n        ops: &[")
    for op in ops:
        print(f"            {op},")
    print("        ],\n    },")
print("];")
print(f"// {len(cases)} cases", file=sys.stderr)
